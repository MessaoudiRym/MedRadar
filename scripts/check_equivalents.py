"""Show the equivalents found for some brand names, to check them by hand.

Reads data/clean/medicaments.csv (run clean_nomenclature.py first).

Usage:
    python scripts/check_equivalents.py
    python scripts/check_equivalents.py GLUCOPHAGE LEVOTHYROX
    python scripts/check_equivalents.py --markdown docs/verification_equivalents.md
"""

import argparse
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
CLEAN_FILE = ROOT / "data" / "clean" / "medicaments.csv"

DEFAULT_BRANDS = [
    "LEVOTHYROX", "GLUCOPHAGE", "DIAMICRON", "AMLOR", "BISOTAB",
    "TAHOR", "DEPAKINE", "TEGRETOL", "COZZAR", "INEXIUM",
]


def load():
    df = pd.read_csv(CLEAN_FILE, dtype=str, keep_default_na=False)
    for col in ("disponible_officine", "exclu", "dosage_verifie"):
        df[col] = df[col] == "True"
    return df


def find_presentations(df, brand):
    """Rows whose brand name is the given name, or starts with it ("GLUCOPHAGE 850")."""
    brand = brand.strip().upper()
    names = df["nom_marque"]
    return df[(names == brand) | names.str.startswith(brand + " ")]


def find_equivalents(df, row):
    """Other brands with the same key, sold in pharmacies and not withdrawn."""
    same_key = df[
        (df["equivalence_key"] == row["equivalence_key"])
        & (df["nom_marque"] != row["nom_marque"])
        & df["disponible_officine"]
        & ~df["exclu"]
        & (df["dosage_norm"] != "")
    ]
    return same_key.drop_duplicates("nom_marque").sort_values("nom_marque")


def describe(row):
    return f"{row['nom_marque']} — {row['dci']} — {row['dosage']} — {row['forme']}"


def status(row):
    notes = []
    if not row["disponible_officine"]:
        notes.append("hospital only")
    if row["exclu"]:
        notes.append("withdrawn / not renewed")
    if not row["dosage_verifie"]:
        notes.append("dose not parsed")
    return f" ({', '.join(notes)})" if notes else ""


def report(df, brands):
    """Build the report as a list of (presentation, equivalents) per brand."""
    results = []
    for brand in brands:
        presentations = find_presentations(df, brand)
        results.append((brand, [(row, find_equivalents(df, row))
                                for _, row in presentations.iterrows()]))
    return results


def print_report(results):
    for brand, items in results:
        print("=" * 70)
        print(brand)
        if not items:
            print("  Aucune présentation trouvée.")
        for row, equivalents in items:
            print(f"\n  {describe(row)}{status(row)}")
            print(f"  Clé : {row['equivalence_key']}")
            print(f"  {len(equivalents)} équivalent(s)")
            for _, eq in equivalents.iterrows():
                print(f"    - {eq['nom_marque']} | {eq['dci']} | {eq['dosage']} | "
                      f"{eq['forme']} | {eq['laboratoire']}")
        print()


def write_markdown(results, path):
    lines = [
        "# Equivalents check",
        "",
        "Generated by `scripts/check_equivalents.py`. Tick each equivalent "
        "once a pharmacist has confirmed it.",
        "",
        "Medicine names, active ingredients, doses, forms and laboratories are "
        "copied as written in the official nomenclature (French).",
        "",
        "Checked by: _name, role_ — Date: _date_",
        "",
    ]
    for brand, items in results:
        lines.append(f"## {brand}")
        lines.append("")
        if not items:
            lines += ["No presentation found.", ""]
        for row, equivalents in items:
            lines.append(f"### {describe(row)}{status(row)}")
            lines.append("")
            lines.append(f"Key: `{row['equivalence_key']}` — {len(equivalents)} equivalent(s)")
            lines.append("")
            for _, eq in equivalents.iterrows():
                lines.append(f"- [ ] **{eq['nom_marque']}** — {eq['dci']} — {eq['dosage']} — "
                             f"{eq['forme']} — {eq['laboratoire']}")
            lines.append("")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Markdown written: {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("brands", nargs="*", default=DEFAULT_BRANDS,
                        help="noms de marque à vérifier")
    parser.add_argument("--markdown", metavar="FICHIER",
                        help="écrire aussi le résultat en Markdown avec des cases à cocher")
    args = parser.parse_args()

    results = report(load(), args.brands)
    print_report(results)
    if args.markdown:
        write_markdown(results, args.markdown)


if __name__ == "__main__":
    main()
